# This script prompts the user for two integers and
# calculates their sum, product, and difference using basic arithmetic operators.

# Request the first integer from the user and convert the string input to an int
first_number = int(input("Enter the first number: "))

# Request the second integer from the user and convert the string input to an int
second_number = int(input("Enter the second number: "))

# Calculate and display the sum (addition) of the two variables
print("The sum of the two numbers is: ", first_number + second_number)

# Calculate and display the product (multiplication) of the two variables
print("The product of the two numbers is: ", first_number * second_number)

# Calculate and display the difference (subtraction) between the two variables
print("The difference between the two numbers is: ", first_number - second_number)